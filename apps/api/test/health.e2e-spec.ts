import type { INestApplication } from '@nestjs/common'
import request from 'supertest'
import { buildTestApp } from './utils/build-test-app'

// The only way to actually verify the Phase 13 health/readiness logic runs
// correctly over real HTTP in this environment: there is no live Postgres
// or Redis to boot the compiled app against (see docs/migration-plan.md),
// so this drives the real HealthController/HealthService through supertest
// with PrismaService/RedisService swapped for controllable fakes.
describe('Health endpoints (e2e)', () => {
  let app: INestApplication | undefined

  afterEach(async () => {
    await app?.close()
    app = undefined
  })

  it('GET /health/live always reports ok, independent of any dependency', async () => {
    app = await buildTestApp()
    const res = await request(app.getHttpServer()).get('/health/live')
    expect(res.status).toBe(200)
    expect(res.body).toEqual({ status: 'ok' })
  })

  it('GET /health/ready reports 200 ok when Postgres and Redis both respond', async () => {
    app = await buildTestApp({
      prisma: { client: { $queryRaw: jest.fn().mockResolvedValue([{ '?column?': 1 }]) } },
      redis: { client: { ping: jest.fn().mockResolvedValue('PONG') } },
    })
    const res = await request(app.getHttpServer()).get('/health/ready')
    expect(res.status).toBe(200)
    expect(res.body).toEqual({ status: 'ok', checks: { database: 'ok', redis: 'ok' } })
  })

  it('GET /health/ready reports 503 when the database is unreachable, without leaking the underlying error', async () => {
    app = await buildTestApp({
      prisma: { client: { $queryRaw: jest.fn().mockRejectedValue(new Error('P1001: connection refused at 10.0.0.5:5432')) } },
      redis: { client: { ping: jest.fn().mockResolvedValue('PONG') } },
    })
    const res = await request(app.getHttpServer()).get('/health/ready')
    expect(res.status).toBe(503)
    expect(res.body).toEqual({ status: 'error', checks: { database: 'error', redis: 'ok' } })
    expect(JSON.stringify(res.body)).not.toContain('10.0.0.5')
  })

  it('GET /health/ready reports 503 when Redis is unreachable, since auth depends on it', async () => {
    app = await buildTestApp({
      prisma: { client: { $queryRaw: jest.fn().mockResolvedValue([{ '?column?': 1 }]) } },
      redis: { client: { ping: jest.fn().mockRejectedValue(new Error('ECONNREFUSED')) } },
    })
    const res = await request(app.getHttpServer()).get('/health/ready')
    expect(res.status).toBe(503)
    expect(res.body.checks.redis).toBe('error')
  })

  it('every response carries a request id header, generated by the real RequestIdMiddleware', async () => {
    app = await buildTestApp()
    const res = await request(app.getHttpServer()).get('/health/live')
    expect(res.headers['x-request-id']).toBeTruthy()
  })
})
